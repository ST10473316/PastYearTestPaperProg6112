    // Load product sales and display report
    private void loadData() {

        int[][] data = sales.GetProductSales();

        StringBuilder report = new StringBuilder();

        report.append("PRODUCT SALES REPORT\n");
        report.append("----------------------------------------\n");

        report.append("Total sales: ")
              .append(sales.GetTotalSales())
              .append("\n");

        report.append(String.format(
                "Average sales: %.2f%n",
                sales.GetAverageSales()));

        report.append("Sales over limit: ")
              .append(sales.GetSalesOverLimit())
              .append("\n");

        report.append("Sales under limit: ")
              .append(sales.GetSalesUnderLimit())
              .append("\n");

        // Display report
        txtReport.setText(report.toString());

        // Display years processed
        lblYearsTitle.setText(
                "Years Processed: " + data.length);
    }
    
        // Save the displayed report to a text file
    private void saveData() {

        if (txtReport.getText().isBlank()) {
            JOptionPane.showMessageDialog( this, "Load product data before saving.");
            return;
        }

        try (FileWriter writer = new FileWriter("data.txt")) {
            writer.write(txtReport.getText());
            JOptionPane.showMessageDialog( this, "Report saved successfully to data.txt");

        } catch (IOException ex) {
            JOptionPane.showMessageDialog( this, "Could not save: " + ex.getMessage()); }
    }
    
    // Clear the report
    private void clearData() {

        txtReport.setText("");
        lblYearsTitle.setText("Years Processed:");
    }
